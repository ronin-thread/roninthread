const params =
    new URLSearchParams(window.location.search);

const id =
    params.get("id");

const product =
    products[id];

if (!product) {

    document.body.innerHTML =
        "<h1>Product Not Found</h1>";
}

document.title =
    product.title + " | Ronin Thread";

document.getElementById(
    "productTitle"
).textContent =
    product.title;

document.getElementById(
    "productCollection"
).textContent =
    product.collection;

document.getElementById(
    "productDescription"
).textContent =
    product.description;

let currentImage = 0;

const imageElement =
    document.getElementById("productImage");

const dotsContainer =
    document.getElementById("sliderDots");

imageElement.src =
    product.image[currentImage];

product.image.forEach((_, index) => {

    const dot =
        document.createElement("div");

    dot.classList.add("dot");

    if (index === 0) {

        dot.classList.add("active");
    }

    dot.addEventListener("click", () => {

        currentImage = index;

        changeImage();
    });

    dotsContainer.appendChild(dot);

});

document.getElementById(
    "buyButton"
).href =
    product.link;

const collectionMap = {

    "RONIN": "ronin",

    "ENSO": "enso",

    "NEON SHOGUN": "neon-shogun"

};

document.getElementById("backLink").href =
    `collection.html?id=${collectionMap[product.collection]}`;

document
    .getElementById("nextBtn")
    .addEventListener("click", () => {

        currentImage++;

        if (currentImage >= product.image.length) {

            currentImage = 0;
        }

        changeImage();

    });


document
    .getElementById("prevBtn")
    .addEventListener("click", () => {

        currentImage--;

        if (currentImage < 0) {

            currentImage =
                product.image.length - 1;
        }

        changeImage();

    });

function updateDots() {

    const dots =
        document.querySelectorAll(".dot");

    dots.forEach(dot => {

        dot.classList.remove("active");
    });

    dots[currentImage]
        .classList.add("active");
}

function changeImage() {

    imageElement.classList.add("fade-out");

    setTimeout(() => {

        imageElement.src = product.image[currentImage];

        imageElement.classList.remove("fade-out");
        updateDots();

    }, 300);
}

document.title = `${product.title} | Ronin Thread`;

document
    .querySelector('meta[name="description"]')
    .setAttribute(
        "content",
        `${product.title} from the ${product.collection} collection. Premium Japanese-inspired streetwear by Ronin Thread.`
    );